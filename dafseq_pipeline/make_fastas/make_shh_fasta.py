# Helper to extract sequence from BedTool
def get_seq(chrom, start, end):
    # bed = pybedtools.BedTool(f"{chrom}\t{start}\t{end}", from_string=True)
    return str(pybedtools.BedTool.seq((chrom, start, end), genome))


# Parse coordinates
