def chrome_parser(chrom_str):
    chrom, coords = chrom_str.split(":")
    start, end = map(int, coords.split("-"))
    return chrom, start, end


def region_setup(enh_l, enh_r, center_len):
    seq_len = enh_l_len + enh_r_len  # __left__mEm_center_mEm__right__
    half_loci_size = int((131072 - (seq_len + center_len)) / 2)

    l_start = half_loci_size
    l_end = l_start + enh_l_len
    r_start = l_end + center_len
    score_regions = [(l_start, l_end), (r_start, r_start + enh_r_len)]
    return score_regions


def setup_obj_helper(file_name, enhs):
    setup_obj = {}

    for name, l, r in enhs:
        chrom, start_l, end_l = chrome_parser(l)
        chrom, start_r, end_r = chrome_parser(r)
        center = start_r - end_l
        l_size = end_l - start_l
        r_size = end_r - start_r

        example_line = {
            "survivors": 4,
            "children_per": 500,
            "mut_rates": [1.0],  # X.Y -- X=number of mutations per enh Y=percent that are dups
            "enh_r_len": r_size,
            "enh_l_len": l_size,
            "enh_l": l,
            "enh_r": r,
            "margin": 0,
            "center_len": center,
        }
        replicates = list(map(lambda x: "rep" + str(x + 1), range(1)))
        #
        #
        # For mut rate adjustment based on enh size

        for rep in replicates:
            line_name = name + "_" + rep
            new_line = copy.deepcopy(example_line)
            setup_obj[line_name] = new_line
    with open("json/" + file_name, "w") as file:
        file.write(json.dumps(setup_obj))
    for i in setup_obj:
        print(i, setup_obj[i])
    print(file_name)
    return setup_obj


